const dictionaries: Record<LocaleId, Record<MessageKey, string>> = { en, ko }

export function translate(locale: string | undefined, key: MessageKey, params?: Record<string, string | number>): string {
  const table = dictionaries[(locale ?? 'en') as LocaleId] ?? en
  const text = table[key] ?? en[key]
  return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : text
}

export function useT() {
  const locale = useSession((state) => state.preference?.locale)
  return (key: MessageKey, params?: Record<string, string | number>) => translate(locale, key, params)
}
