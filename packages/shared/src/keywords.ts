export function keywordHash(word: string): string {
  return createHash('sha256').update(word.toLowerCase()).digest('hex')
}

export function pickWeeklyKeyword(
  recentHashes: Iterable<string>,
  rng: (max: number) => number = (max) => randomInt(max),
): string {
  const recent = new Set(recentHashes)
  const fresh = WEEKLY_KEYWORDS.filter((word) => !recent.has(keywordHash(word)))
  const pool = fresh.length > 0 ? fresh : WEEKLY_KEYWORDS
  const index = rng(pool.length)
  const word = pool[index]
  if (!word) throw new Error('Weekly keyword pool is empty')
  return word
}
